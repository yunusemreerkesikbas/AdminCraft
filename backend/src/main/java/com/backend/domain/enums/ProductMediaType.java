package com.backend.domain.enums;

/**
 * Types of media associated with products.
 */
public enum ProductMediaType {
  /**
   * Primary/main image for the product
   */
  PRIMARY,

  /**
   * Gallery images for the product
   */
  GALLERY,

  /**
   * Thumbnail image
   */
  THUMBNAIL,

  /**
   * Video media
   */
  VIDEO,

  /**
   * Document/PDF attachments
   */
  DOCUMENT
}
