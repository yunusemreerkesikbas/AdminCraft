CREATE TABLE commerce_customer_addresses (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    uuid VARCHAR(36) NOT NULL,
    uid VARCHAR(50) NOT NULL,
    customer_id BIGINT NOT NULL,
    label VARCHAR(100) NULL,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    country_iso VARCHAR(2) NOT NULL DEFAULT 'TR',
    city VARCHAR(100) NOT NULL,
    district VARCHAR(100) NOT NULL,
    address_line1 VARCHAR(255) NOT NULL,
    address_line2 VARCHAR(255) NULL,
    postal_code VARCHAR(20) NULL,
    default_delivery BOOLEAN NOT NULL DEFAULT FALSE,
    default_billing BOOLEAN NOT NULL DEFAULT FALSE,
    invoice_type VARCHAR(20) NOT NULL DEFAULT 'INDIVIDUAL',
    company_name VARCHAR(200) NULL,
    tax_number VARCHAR(50) NULL,
    tax_office VARCHAR(100) NULL,
    invoice_identity_number VARCHAR(50) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    created_by BIGINT NULL,
    updated_by BIGINT NULL,
    CONSTRAINT uk_commerce_customer_address_uuid UNIQUE (uuid),
    CONSTRAINT uk_commerce_customer_address_uid UNIQUE (uid),
    CONSTRAINT fk_commerce_customer_address_customer FOREIGN KEY (customer_id)
        REFERENCES commerce_customers(id) ON DELETE CASCADE,
    CONSTRAINT chk_commerce_customer_address_invoice_type CHECK (invoice_type IN ('INDIVIDUAL', 'CORPORATE')),
    INDEX idx_commerce_customer_address_customer (customer_id),
    INDEX idx_commerce_customer_address_delivery (customer_id, default_delivery),
    INDEX idx_commerce_customer_address_billing (customer_id, default_billing)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

